import Foundation

public enum AudioRecorderError: LocalizedError {
    case ffmpegNotFound(String)
    case recordingAlreadyInProgress
    case recordingNotActive
    case recordingTooShort(Double)
    case outputFileNotFound
    case processFailed(Int32)

    public var errorDescription: String? {
        switch self {
        case .ffmpegNotFound(let path):
            return "ffmpeg executable not found at '\(path)'. Please install ffmpeg via 'brew install ffmpeg'."
        case .recordingAlreadyInProgress:
            return "Audio recording is already active."
        case .recordingNotActive:
            return "No active audio recording to stop."
        case .recordingTooShort(let duration):
            return String(format: "Recording was too short (%.2fs). Tap ignored.", duration)
        case .outputFileNotFound:
            return "Recorded audio file was not generated by ffmpeg."
        case .processFailed(let code):
            return "ffmpeg exited unexpectedly with code \(code)."
        }
    }
}

public final class AudioRecorder {
    private var process: Process?
    private var currentTempFile: URL?
    private var recordingStartTime: Date?
    private let queue = DispatchQueue(label: "com.typeless.audiorecorder", qos: .userInitiated)

    public var isRecording: Bool {
        return process?.isRunning == true
    }

    public init() {}

    public func startRecording(config: AppConfig) throws {
        try queue.sync {
            if process?.isRunning == true {
                throw AudioRecorderError.recordingAlreadyInProgress
            }

            guard FileManager.default.isExecutableFile(atPath: config.ffmpegPath) else {
                throw AudioRecorderError.ffmpegNotFound(config.ffmpegPath)
            }

            let tempDir = FileManager.default.temporaryDirectory
            let fileName = "typeless_\(UUID().uuidString).wav"
            let fileURL = tempDir.appendingPathComponent(fileName)
            self.currentTempFile = fileURL

            let proc = Process()
            proc.executableURL = URL(fileURLWithPath: config.ffmpegPath)
            proc.arguments = [
                "-nostdin",
                "-loglevel", "error",
                "-f", "avfoundation",
                "-i", config.audioDevice,
                "-ar", "16000",
                "-ac", "1",
                "-c:a", "pcm_s16le",
                "-y",
                fileURL.path
            ]

            let pipe = Pipe()
            proc.standardError = pipe
            proc.standardOutput = pipe

            try proc.run()
            self.process = proc
            self.recordingStartTime = Date()
        }
    }

    public func stopRecording(config: AppConfig) throws -> URL {
        return try queue.sync {
            guard let proc = self.process, proc.isRunning, let fileURL = self.currentTempFile else {
                throw AudioRecorderError.recordingNotActive
            }

            let duration = Date().timeIntervalSince(self.recordingStartTime ?? Date())
            let pid = proc.processIdentifier

            // Clean up internal references immediately
            self.process = nil
            self.recordingStartTime = nil
            self.currentTempFile = nil

            if duration < config.minRecordingDurationSeconds {
                kill(pid, SIGTERM)
                try? FileManager.default.removeItem(at: fileURL)
                throw AudioRecorderError.recordingTooShort(duration)
            }

            // Send SIGINT so ffmpeg cleanly writes the WAV header and finishes
            kill(pid, SIGINT)

            // Wait with a timeout
            let deadline = Date().addingTimeInterval(2.0)
            while proc.isRunning && Date() < deadline {
                usleep(50_000) // 50ms
            }

            if proc.isRunning {
                kill(pid, SIGKILL)
            }

            guard FileManager.default.fileExists(atPath: fileURL.path) else {
                throw AudioRecorderError.outputFileNotFound
            }

            // Check file size (valid wav needs to be > 44 bytes)
            if let attrs = try? FileManager.default.attributesOfItem(atPath: fileURL.path),
               let size = attrs[.size] as? UInt64, size > 44 {
                return fileURL
            } else {
                try? FileManager.default.removeItem(at: fileURL)
                throw AudioRecorderError.recordingTooShort(duration)
            }
        }
    }

    public func cancel() {
        queue.sync {
            if let proc = self.process, proc.isRunning {
                kill(proc.processIdentifier, SIGKILL)
            }
            if let file = self.currentTempFile {
                try? FileManager.default.removeItem(at: file)
            }
            self.process = nil
            self.currentTempFile = nil
            self.recordingStartTime = nil
        }
    }
}
